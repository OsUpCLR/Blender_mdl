def L(s):
    """Return Russian UI text when Blender language is Russian."""
    try:
        import bpy
        lang = str(bpy.context.preferences.view.language or "en_US")
    except Exception:
        lang = "en_US"
    if lang.lower().startswith("ru"):
        return RU.get(s, s)
    return s
